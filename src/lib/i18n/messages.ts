const ALL: Record<Locale, Messages> = { ko, en };

export function getMessages(locale: Locale): Messages {
  return ALL[locale];
}

/** "5시간 전" / "5h ago" */
export function relativeTime(m: Messages, dateStr: string): string {
  const diffHours = Math.floor((Date.now() - new Date(dateStr).getTime()) / 3_600_000);
  if (diffHours < 1) return m.time.justNow;
  if (diffHours < 24) return m.time.hoursAgo(diffHours);
  return m.time.daysAgo(Math.floor(diffHours / 24));
}

/** "5시간" / "5h" (짧게) */
export function relativeTimeShort(m: Messages, dateStr: string): string {
  const diffHours = Math.floor((Date.now() - new Date(dateStr).getTime()) / 3_600_000);
  if (diffHours < 1) return m.time.nowShort;
  if (diffHours < 24) return m.time.hoursShort(diffHours);
  return m.time.daysShort(Math.floor(diffHours / 24));
}
